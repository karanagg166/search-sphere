"""Standalone storage cannot select a legacy or misspelled backend."""

import pytest

from src.config import settings
from src.vector_store import get_vector_store
from src.vector_store.contracts import VectorStoreError, generate_point_id
from src.vector_store.supabase_vector_store import SupabaseVectorStoreError


@pytest.mark.parametrize("backend", ["qdrant", "unknown", "supabse", ""])
def test_unsupported_backend_fails_before_any_network_or_fallback(monkeypatch, backend):
    monkeypatch.setattr(settings, "VECTOR_STORE_BACKEND", backend)
    with pytest.raises(ValueError, match="PostgreSQL/pgvector"):
        get_vector_store()


def test_pgvector_keeps_existing_chunk_id_and_common_failure_contract():
    # UUID previously generated by the archived adapter for this exact identity.
    assert generate_point_id("public-fixture", 0) == "96ff25c1-65e3-5031-aef1-cbdfd3a1fe7f"
    assert issubclass(SupabaseVectorStoreError, VectorStoreError)
